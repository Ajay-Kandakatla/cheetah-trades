# ═════════════════════════════════════════════ builders (every count from the capture, by key)
def _recs():
    return [dict(copy.deepcopy(N[s]["si_record"]), _id=s) for s in NAMES]


def _docs(mfloat=False):
    out = []
    for s in NAMES:
        d = copy.deepcopy(N[s]["basis_doc"])
        if d is None:
            continue
        if mfloat:
            d["mfloat"] = SB.mfloat_sub(None, _answer(s), NOW)
        out.append(d)
    return out


def _db(docs=None, extra=()):
    return FakeDB({SIC.SI_COLL: FakeColl(_recs(), name=SIC.SI_COLL),
                   SB.SB_COLL: FakeColl(list(_docs() if docs is None else docs) + list(extra), name=SB.SB_COLL)})


def _answer(s):
    m = N[s]["massive_float"] if s in N else None
    if m is None:
        return {"status": "none"}
    return {"status": "ok", "shares": m["free_float"], "pct": m["free_float_percent"], "as_of": m["effective_date"]}


class Spy:
    def __init__(self, fn=None):
        self.calls, self.fn = [], fn

    def __call__(self, *a, **k):
        self.calls.append((a, k))
        return self.fn(*a, **k) if self.fn else None


def _fetch_fn(syms):
    return {s: _answer(s) for s in syms}


def _widen_fn(sym, d, now=None, store=True):
    """The captured 11-26 splits read laid on from the second float's date (DKI, CWH only — the rest fail)."""
    doc = SB._find_one(d[SB.SB_COLL], sym)
    if not isinstance(doc, dict) or not SB.needs_window(doc):
        return {"status": "not_needed", "splits": None}
    w = CAP["splits_widened"]["names"].get(sym)
    if not w:
        return {"status": "failed", "splits": None}
    md = doc["mfloat"]["as_of"]
    sub = dict(doc["splits"], since=md, rows=[r for r in w["rows"] if r["execution_date"] >= md])
    if store:
        d[SB.SB_COLL].update_one({"_id": sym, "checked_at": {"$exists": True}}, {"$set": {"splits": sub}})
    return {"status": "widened", "splits": sub}


def _groups(listed=NAMES, followed=(), watch=(), faults=()):
    return lambda st, d, now: {"listed": list(listed), "followed": list(followed), "watch": list(watch),
                               "faults": list(faults)}


def _night(st=None, db=None, **kw):
    sink = {}
    args = dict(store=st if st is not None else fake_store(), db=db if db is not None else _db(),
                names_fn=_groups(), fetch=Spy(_fetch_fn), widen=Spy(_widen_fn), refresh=Spy(), sleep=NOSLEEP,
                sink=sink)
    args.update(kw)
    res = SA.audit_night(NOW, **args)
    return res, sink, args


def _row(sink, s):
    return next(r for r in sink["rows"] if r["symbol"] == s)


def _db_writes(db):
    return sum(len(c.writes) for c in db.colls.values())


def _state_writes(st):
    c = st.coll(ST.STATE)
    return list(c.ops) + list(c.docs)                         # every update_one asked + every doc on file


