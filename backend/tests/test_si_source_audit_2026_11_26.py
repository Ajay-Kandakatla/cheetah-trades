def _budget_section(text):
    start = text.index("### Budget and cost")
    return text[start:text.index("\n## ", start)]


def _provenance_faults(text):
    """What the budget section claims about where each number came from, checked against the code and the fixture."""
    sec = _budget_section(text)
    faults = []
    measured = next((p for p in sec.split("\n\n") if p.startswith("**Measured 2026-11-27 01:26 ET")), None)
    if measured is None:
        return ["no measured paragraph"]
    if "needs_window" in measured:
        faults.append("method claims needs_window")
    row = next((ln for ln in sec.splitlines() if ln.startswith("| checked names whose second float")), "")
    for need in ("11-26 probe", "124 of 693", "frozen fixture", "not re-read on 11-27"):
        if need not in row:
            faults.append(f"window row lacks {need!r}")
    if "792 checked basis docs, 0 with a second float" not in sec:
        faults.append("no live 0-mfloat note")
    if "arithmetic on that 11-26 count of 124" not in sec:
        faults.append("96-of-124 not marked as arithmetic")
    return faults


def test_the_budget_table_labels_the_window_row_as_the_frozen_11_26_probe():
    assert _provenance_faults(AUDIT_DOC.read_text(encoding="utf-8")) == []


