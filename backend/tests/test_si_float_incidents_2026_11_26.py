def _flags(b) -> list:
    return [f.get("key") for f in (b.get("basis") or {}).get("flags") or []]


def _rows(b) -> dict:
    return {r["k"]: r["v"] for r in b.get("rows") or []}


def _state(b):
    sc = (b.get("basis") or {}).get("sources_compared")
    return sc.get("state") if isinstance(sc, dict) else None


def _no_mfloat(case) -> dict:
    c = copy.deepcopy(case)
    if isinstance(c["basis_doc"], dict):
        c["basis_doc"].pop("mfloat", None)
    return c


def _sck_strings(b) -> list:
    """Every string the source check wrote (the words of THIS build; SEC exhibit titles are served verbatim)."""
    basis = b.get("basis") or {}
    sc = basis.get("sources_compared") if isinstance(basis.get("sources_compared"), dict) else {}
    out = [sc.get("text") or ""] + [r["v"] for r in b.get("rows") or [] if r["k"] == SCK.ROW_FLOAT_SOURCES]
    out += [f.get("text") or "" for f in basis.get("flags") or [] if f.get("key") == SCK.FLAG_SOURCES]
    out += [s for s in (b.get("title") or "").split(". ") if SCK.HOVER_HEAD in s or SCK.SHORT_SOURCES in s]
    return out


def _strings(b) -> list:
    out = [b.get("chip") or "", b.get("title") or ""] + [r["k"] + " " + r["v"] for r in b.get("rows") or []]
    e = b.get("extreme") or {}
    out += [e.get(k) or "" for k in ("text", "short", "title")]
    out += [f.get("text") or "" for f in (b.get("basis") or {}).get("flags") or []]
    return out


