# THE BANNER — prose built from MEASURED, no number typed anywhere else
# ═════════════════════════════════════════════════════════════════════════════
def measured_verdict() -> dict:
    """{headline, body, fallback_note, limits} — what the board leads with.

    The word is REVERSAL. Nothing in here says "bounc…".
    """
    m = MEASURED
    st = m.get("status")
    # The MAX over the three splits, not `s1`'s — see `binding_mdl`. The chip
    # payload (`measured_block`) and the ℹ️ Rules panel read the same call, so
    # the three surfaces cannot drift apart again (critique B1).
    mdl = binding_mdl()
    fallback_note = (
        "Ordered by his two asks, in the order he asked them: the ceiling "
        "first, then the floor as the tiebreak — a second band closest under "
        "the first, then the bigger first band. The ceiling leg has THREE "
        "groups, not one scale: a name with nothing PROVEN overhead is "
        "UNTESTED rather than thin (fewer than %d touches up there, so the "
        "wall is uncounted, not absent — the stat says which untested band is "
        "nearest and whether the print is standing in it), then the names "
        "whose first wall can actually be measured, thinnest first, then the "
        "ones whose ceiling cannot be read at all. WHICH END THE UNTESTED "
        "GROUP BELONGS ON IS AN OPEN QUESTION — it leads today because that "
        "is what shipped, and nobody has measured it either way. All of this "
        "is a DESCRIPTIVE ordering of what the bands look like, not a claim "
        "that a thin ceiling or a layered floor makes a name go up. Because "
        "it is lexicographic the ceiling settles nearly every pair and the "
        "floor only breaks ties. A name with no band read sorts last, never "
        "first." % LID_MIN_TOUCHES)

    if st == STATUS_PENDING:
        headline = ("MEASURED: pending — ordered by ceiling thickness, floor "
                    "layering as the tiebreak, until the study lands")
        body = ("The replay behind this read is still running (%s). Until it "
                "lands nothing here is scored: the stat is descriptive, the "
                "order is the fallback, and no number is quoted. What IS "
                "already measured and is NOT re-stated by this ordering: the "
                "2026-09-07 lid-break study found DISTANCE decides whether a "
                "lid clears, so a thin-ceiling claim only means something "
                "inside a distance bucket — which is what the study is "
                "measuring." % m.get("script"))
    elif st == STATUS_SEPARATES:
        headline = ("MEASURED %s: %s separates on %s episodes, OOS on 3 splits"
                    % (m.get("run_date"), ", ".join(SELECTED) or "nothing",
                       "{:,}".format(m.get("n_episodes") or 0)))
        body = ("Measured on %s episodes in %s, %s names, %s. The score is the "
                "oriented percentile rank of %s against the edges frozen on "
                "the first date half; a live read never re-fits. %s"
                % ("{:,}".format(m.get("n_episodes") or 0), m.get("window"),
                   "{:,}".format(m.get("n_names") or 0), m.get("universe_mode"),
                   ", ".join(SELECTED) or "nothing", _prose(m.get("cohort_note"))))
        fallback_note = ("Names without a band read — no doc, no bands, or a "
                         "tab whose rows are not bands — sort last, never "
                         "first.")
    else:
        headline = ("MEASURED %s: NO SIGNAL SEPARATES%s — ordered by ceiling "
                    "thickness, floor layering as the tiebreak"
                    % (m.get("run_date"),
                       (" (no lift larger than %.2fpp)" % mdl) if mdl is not None else ""))
        body = ("Measured on %s episodes in %s, %s names, %s. Neither a thin "
                "first lid nor a layered floor survived the rule of reading on "
                "all three out-of-sample splits, so there is no score and the "
                "board says so. %s"
                % ("{:,}".format(m.get("n_episodes") or 0), m.get("window"),
                   "{:,}".format(m.get("n_names") or 0), m.get("universe_mode"),
                   _prose(m.get("cohort_note"))))

    limits = ("Bands are BOARD geometry on CLOSED bars — the live session's "
              "own high and low are not in them, and an unproven lid (fewer "
              "than %d touches) is not counted overhead at all, here or "
              "anywhere else. A band the engine did not cluster is not a band "
              "that is not there. %s This is a board ordering and a stat — it "
              "gates no alert, sizes no position and enters no lane."
              % (LID_MIN_TOUCHES, BOARD_SCOPE_NOTE))

    script = str(m.get("script") or "")
    if script and script not in body:
        body = body.rstrip() + " Re-runnable verbatim: %s." % script
    return {"headline": headline, "body": body,
            "fallback_note": fallback_note, "limits": limits}
