def _f(x) -> Optional[float]:
    """Numbers only: NaN / inf / junk become None (the `alert_gates._f` rule)."""
    try:
        v = float(x)
    except (TypeError, ValueError):
        return None
    return v if v == v and not math.isinf(v) else None


def _prose(s) -> str:
    """Prose he reads says REVERSAL, never bounce (2026-09-09 rule). The
    engines keep `bouncing` internally on purpose, so the translation happens
    at the one place a served string becomes a sentence."""
    return str(s or "").replace("bouncing", "reversal").replace("bounce", "reversal")


def status() -> str:
    """The EFFECTIVE status. `separates` only when the dict actually carries
    what a live rank needs — the selected reads, their orientation and their
    frozen edges. Anything else (pending, null, half-written) reads as the
    fallback rather than inventing a rank. The `explosive.status()` rule."""
    st = MEASURED.get("status")
    if st == STATUS_PENDING:
        return STATUS_PENDING
    if st != STATUS_SEPARATES:
        return STATUS_NO_SIGNAL
    orient = MEASURED.get("orientation") or {}
    edges = MEASURED.get("edges") or {}
    if not SELECTED or any(k not in orient for k in SELECTED):
        log.warning("band_structure: MEASURED says separates but selected/"
                    "orientation is incomplete — falling back to %s",
                    ",".join(FALLBACK_KEYS))
        return STATUS_NO_SIGNAL
    if any(k not in edges for k in SELECTED):
        log.warning("band_structure: MEASURED says separates but edges are "
                    "missing — falling back to %s", ",".join(FALLBACK_KEYS))
        return STATUS_NO_SIGNAL
    return STATUS_SEPARATES


