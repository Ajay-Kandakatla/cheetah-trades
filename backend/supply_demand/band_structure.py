# THE PER-NAME READ — one band selection, every surface
# ═════════════════════════════════════════════════════════════════════════════
def kind_for_tab(tab) -> str:
    """The tab's kind, from `enterable.KIND_BY_TAB` — ONE map, not a second
    one. A tab nobody listed is n/a: a new tab must be added there on purpose
    rather than inheriting a band ordering by omission."""
    from supply_demand import enterable as EN                    # noqa: PLC0415
    return EN.KIND_BY_TAB.get(str(tab or ""), EN.KIND_NA)


def _print_block(px, print_source) -> dict:
    """WHICH PRINT THIS READ IS ABOUT, carried the way the 🎯 read carries it
    (`enterable.assess` -> `read["print"]["source"]`, fed from
    `bounce_room.print_of`'s own `fresh` flag).

    Every number in this read — the ceiling distance, the floor distance, both
    heights as a % of the print — is measured FROM this price, and the caller
    is the only one who knows whether it is a live trade or the stored close
    the snapshot fell back to. `None` when the caller did not say: an unknown
    source is served as unknown, never asserted as "live" (critique m1).
    """
    src = str(print_source) if print_source else None
    return {"px": _f(px), "source": src}


def read(*, doc=None, px=None, symbol=None, kind=None,
         print_source=None) -> Optional[dict]:
    """The per-name read. `kind` comes from `enterable.KIND_BY_TAB`.

    * `KIND_NA` -> an APPLICABLE-FALSE read that says why, and no band work at
      all (the store is never touched). The 🎯 n/a precedent: an honest "this
      tab is not that" beats a fake ordering.
    * anything else -> the ceiling half and the floor half off the SAME doc
      and the SAME print.

    `print_source` — "live" or "scan", the same two words the 🎯 read carries,
    from the caller that chose the price. OPTIONAL and defaulting to None
    rather than to "live": a caller that cannot say which print it handed in
    must not have "live" asserted on its behalf over a stored close.

    None when there is no doc at all — an absent read sorts last and hides the
    stat, which is the honest answer for a name the store has not warmed.
    """
    from supply_demand import enterable as EN                    # noqa: PLC0415

    sym = str(symbol or "").upper()
    k = str(kind or EN.KIND_DEMAND)
    if k == EN.KIND_NA:
        out = {"symbol": sym, "kind": k, "applicable": False, "ceiling": None,
               "floor": None, "score": None, "na_text": NA_TEXT,
               "print": _print_block(px, print_source),
               "measured": measured_block()}
        out["stat"] = stat_line(out)
        return out
    p = _f(px)
    if p is None or p <= 0 or not isinstance(doc, dict) or not doc:
        return None
    # A doc with NO bands at all is an UNKNOWN, not a clear ceiling.
    # `bounce_room.room_read` answers CLEAR for it — correctly, for its own
    # question ("is anything proven overhead?") — and taking that answer here
    # would put a name the engine could not cluster FIRST on a board that
    # ranks thin ceilings. No bands, no read.
    if not (doc.get("bands") or []):
        return None
    ceiling = ceiling_read(p, doc)
    floor = floor_read(p, doc)
    if ceiling is None and floor is None:
        return None
    out = {"symbol": sym, "kind": k, "applicable": True, "ceiling": ceiling,
           "floor": floor, "score": None, "na_text": None,
           "print": _print_block(p, print_source),
           "measured": measured_block()}
    out["stat"] = stat_line(out)
    return out


def binding_mdl() -> Optional[float]:
    """THE RESOLUTION EVERY SURFACE IS ALLOWED TO QUOTE: the MAX over the three
    out-of-sample splits, never split `s1`'s alone.

    Nothing was selected on ALL THREE splits, so the smallest lift this study
    could have seen anywhere is the WEAKEST split's — the max of the three
    detectable lifts, not the first one. Serving `s1` (2.51pp) understated the
    study's own resolution by 0.29pp and put the board banner and the ℹ️ Rules
    panel in direct contradiction with the run file (`q1.mdl`), the
    methodology doc and the ✨ label, all three of which quote 2.80pp
    (critique B1, 2026-09-16).

    It is the same `max()` the run itself takes across splits — the shipped
    JSON's own `derived_for_module` note says `splits[k].mdl =
    max(q1.splits[k].mdl, q2.splits[k].mdl)` — so the max over the served
    splits is by construction `MEASURED["q1"]["mdl"]`. Pinned both ways in
    `tests/test_band_structure_2026_09_16.py`.
    """
    vals = [_f((s or {}).get("mdl"))
            for s in (MEASURED.get("splits") or {}).values()]
    vals = [v for v in vals if v is not None]
    return max(vals) if vals else None


def measured_block() -> dict:
    """What every chip tooltip repeats — read from MEASURED, never typed."""
    s1 = (MEASURED.get("splits") or {}).get("s1") or {}
    return {"status": MEASURED.get("status"),
            "run_date": MEASURED.get("run_date"),
            "n_episodes": MEASURED.get("n_episodes"),
            "oos_lift": s1.get("lift"),
            "oos_ci": s1.get("ci"),
            # NOT `s1["mdl"]` — the binding resolution is the max over the
            # three splits (see `binding_mdl`), the same number the banner and
            # the ℹ️ Rules panel quote.
            "mdl": binding_mdl(),
            "script": MEASURED.get("script")}


