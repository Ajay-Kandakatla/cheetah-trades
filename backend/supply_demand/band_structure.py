# THE CEILING HALF — his ask #1, "the thinnest over head or Supply zone"
# ═════════════════════════════════════════════════════════════════════════════
def ceiling_read(px, doc) -> Optional[dict]:
    """What price meets FIRST going up, and how much of a wall it is.

    The band selection is `bounce_room.room_read` verbatim — unbroken supply
    at/above the print plus demand bands price has fallen through (broken
    support = resistance), skipping bands nobody has tested
    (`alert_gates.is_proven_band`, the KLAC lesson). So the ceiling served here
    is the SAME band the room gate, the boards and the 🧨 chip already name —
    an untested lid still never becomes the CEILING. What is different here is
    that it is not silently invisible either: a board that RANKS on thinness
    would otherwise put "nobody has tested it" ahead of "somebody measured it",
    so the nearest untested band rides along beside the answer.

    {state, band, height_pct, distance_pct, walls_above, walls_to_high,
     at_highs, untested_band, untested_distance_pct, in_untested_band}.

    `state == "CLEAR"` means nothing PROVEN overhead — UNTESTED, never
    "nothing overhead". So the three `untested_*` fields ride along: the
    nearest band the engine skipped for want of touches, how far up it is, and
    whether the print is standing INSIDE it. They are served whenever price
    meets that untested band BEFORE the proven ceiling (always, when the state
    is CLEAR); behind a proven wall they are omitted, because the proven wall
    is the one every other surface names. `stat_line` says all of this in
    words — no surface re-derives it. None when the print is unusable.
    """
    from supply_demand import bounce_room as BR                  # noqa: PLC0415

    p = _f(px)
    if p is None or p <= 0:
        return None
    doc = doc or {}
    room = BR.room_read(p, doc)
    if not isinstance(room, dict):
        return None
    overhead = BR.overhead_bands(doc.get("bands") or [], p, doc.get("prev_close"))
    h252 = _f(doc.get("high_252"))
    # walls between the print and the 52-week high: the lids that still have to
    # be cleared before the name is at new highs. None (not 0) when the doc
    # carries no 252-bar high — unknown is not "none left".
    walls_to_high = None
    if h252 is not None and h252 > 0:
        walls_to_high = sum(1 for b in overhead
                            if (_lohi(b)[0] or 0.0) <= h252 * NEW_HIGH_TOL)
    band = room.get("band")
    # The nearest band the engine skipped for want of touches. Kept only when
    # price meets it BEFORE the proven ceiling: behind a proven wall it changes
    # nothing he can act on, and naming it there would put two ceilings in one
    # sentence. CRDO 2026-09-16 is both cases — every band 1-touch (state
    # CLEAR, the print standing inside an untested supply shelf), and live the
    # same day a proven lid far above with an untested band just over the
    # print. Those numbers live in the tests and the doc, never here.
    untested = BR.first_overhead(_untested_overhead(doc, p), p)
    if untested is not None and band is not None:
        if float(untested["lo"]) >= float(band["lo"]):
            untested = None
    in_untested, u_dist = False, None
    if untested is not None:
        u_lo, u_hi = float(untested["lo"]), float(untested["hi"])
        in_untested = bool(u_lo <= p <= u_hi)
        u_dist = 0.0 if in_untested else round((u_lo / p - 1.0) * 100.0, 2)
    return {"state": room.get("state"),
            "band": _band_block(doc, band, p) if band else None,
            "height_pct": _height_pct(band, p) if band else None,
            "distance_pct": _f(room.get("room_pct")),
            "walls_above": len(overhead),
            "walls_to_high": walls_to_high,
            "at_highs": bool(room.get("at_highs")),
            # touches=None on the way in so `_band_block` reads the REAL touch
            # count off the stored band rather than the count lifted to ask
            # the engine its second question.
            "untested_band": (_band_block(doc, dict(untested, touches=None), p)
                              if untested is not None else None),
            "untested_distance_pct": u_dist,
            "in_untested_band": in_untested}


# ═════════════════════════════════════════════════════════════════════════════
# THE FLOOR HALF — his ask #2, "another one right below it"
# ═════════════════════════════════════════════════════════════════════════════
def floor_read(px, doc) -> Optional[dict]:
    """The catch under the print: the first demand band, and the next one down.

    Band #1 is `bounce_room.demand_read` verbatim (nearest demand band at or
    BELOW the print — a band price has fallen through is overhead, and the
    ceiling half already counts it there). Band #2 is the next demand band
    whose top sits strictly below band #1's floor, i.e. the one he pointed at:
    "another one right below it".

    `gap_pct` = (band1.lo − band2.hi) / print × 100 — how far price would fall
    through the first band before the second one is in play. It is None, never
    0, when there is no second band: "no second catch" and "the second catch
    touches the first" are opposite facts.

    {band, in_band, distance_pct, height_pct, second, gap_pct, bands_below}.
    None when the print is unusable or nothing sits at/below it.
    """
    from supply_demand import bounce_room as BR                  # noqa: PLC0415

    p = _f(px)
    if p is None or p <= 0:
        return None
    doc = doc or {}
    first = BR.demand_read(p, doc)
    if not isinstance(first, dict):
        return None
    lo1, hi1 = _lohi(first)
    if lo1 is None:
        return None
    below = _demand_bands_below(doc, p)
    second = None
    for b in below:
        blo, bhi = _lohi(b)
        if blo is None or bhi >= lo1:
            continue
        second = b
        break
    gap_pct = None
    if second is not None:
        gap_pct = round((lo1 - float(second["hi"])) / p * 100.0, 2)
    return {"band": _band_block(doc, first, p),
            "in_band": bool(first.get("in_band")),
            "distance_pct": _f(first.get("distance_pct")),
            "height_pct": _height_pct(first, p),
            "second": _band_block(doc, second, p) if second is not None else None,
            "gap_pct": gap_pct,
            "bands_below": len(below)}


# ═════════════════════════════════════════════════════════════════════════════
# THE STAT — his words, on every tile and every row
# ═════════════════════════════════════════════════════════════════════════════
def _pct(v) -> str:
    return "%.1f%%" % float(v)


def stat_line(read: Optional[dict]) -> Optional[str]:
    """"ceiling 3.5% wide, 0.5% up · floor 3.2% wide, 2nd band 6.4% under".

    Built from the SERVED numbers only, so no surface re-derives it. None when
    there is nothing to say; the n/a text when the tab has no band read.
    """
    if not isinstance(read, dict):
        return None
    if not read.get("applicable"):
        return NA_TEXT
    parts = []
    c = read.get("ceiling") or {}
    u_dist = _f(c.get("untested_distance_pct"))
    u_band = c.get("untested_band") or {}
    u_height = _f(u_band.get("height_pct"))
    # ONE RANGE, SAID ONCE (critique m2, 2026-09-16). On his own CRDO the store
    # carries a supply cluster AND a demand cluster over ONE range, so the
    # sentence named that range twice — "price inside an untested band N% wide
    # · floor N% wide" reads as two walls when it is one. When the
    # untested band the print is standing in IS the floor band, the ceiling
    # half says which band it is and leaves the width to the floor half, which
    # quotes it one clause later.
    same_as_floor = (bool(c.get("in_untested_band"))
                     and _same_range(u_band, (read.get("floor") or {}).get("band")))
    if c.get("state") == "CLEAR":
        # NOTHING PROVEN OVERHEAD IS NOT NOTHING OVERHEAD. The word is
        # UNTESTED, and the nearest untested band is named — including the one
        # the print is standing in, which is what CRDO was doing on 2026-09-16
        # while the board said "ceiling clear".
        if same_as_floor:
            parts.append("ceiling untested — price inside its floor band")
        elif c.get("in_untested_band"):
            parts.append("ceiling untested — price inside an untested band %s wide"
                         % _pct(u_height) if u_height is not None
                         else "ceiling untested — price inside an untested band")
        elif u_dist is not None:
            parts.append("ceiling untested — nearest untested band %s up" % _pct(u_dist))
        else:
            parts.append("ceiling untested — nothing proven overhead")
    elif c.get("height_pct") is not None:
        d = c.get("distance_pct")
        if c.get("state") == "IN_BAND" or (d is not None and d <= 0):
            line = "ceiling %s wide, price in it" % _pct(c["height_pct"])
        elif d is not None:
            line = "ceiling %s wide, %s up" % (_pct(c["height_pct"]), _pct(d))
        else:
            line = "ceiling %s wide" % _pct(c["height_pct"])
        # An untested band NEARER than the proven one is named too: the live
        # CRDO read quoted the distance to the proven lid while a 1-touch band
        # sat just over the print.
        if same_as_floor:
            line += " (price inside its floor band, untested overhead)"
        elif c.get("in_untested_band"):
            line += " (price inside an untested band)"
        elif u_dist is not None:
            line += " (untested band %s up)" % _pct(u_dist)
        parts.append(line)
    f = read.get("floor") or {}
    if f.get("height_pct") is not None:
        floor = "floor %s wide" % _pct(f["height_pct"])
        if f.get("gap_pct") is not None:
            floor += ", 2nd band %s under" % _pct(f["gap_pct"])
        else:
            floor += ", no 2nd band"
        parts.append(floor)
    if not parts:
        return None
    return " · ".join(parts)


