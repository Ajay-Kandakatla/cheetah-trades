def _kind(band) -> str:
    return str((band or {}).get("kind") or "demand").lower()


def _lohi(band):
    lo, hi = _f((band or {}).get("lo")), _f((band or {}).get("hi"))
    if lo is None or hi is None or not 0 < lo <= hi:
        return None, None
    return lo, hi


def _height_pct(band, px) -> Optional[float]:
    """Band thickness as a % OF THE PRINT — the same unit every room and
    distance number on these boards is quoted in, so "3.5% wide, 0.5% up" is
    two numbers on one scale. None when either end is unreadable."""
    lo, hi = _lohi(band)
    p = _f(px)
    if lo is None or p is None or p <= 0:
        return None
    return round((hi - lo) / p * 100.0, 2)


def _stored_band(doc, band) -> dict:
    """The FULL stored band behind a slimmed one. `bounce_room.overhead_bands`
    drops `strength` (it never needed it); rather than re-deriving a strength
    here — which would be a second definition of `price_zones._strength` — the
    doc's own band is found again by kind and by its exact `lo`/`hi`, which are
    copied through as floats and so compare exactly. `{}` when it cannot be
    matched: an unknown strength is served as None, never as a zero."""
    lo, hi = _lohi(band)
    if lo is None:
        return {}
    kind = _kind(band)
    # a demand band that price fell through is served as `broken_support`
    # overhead — it is still a demand band in the store
    look = "demand" if kind == "broken_support" else kind
    for b in (doc or {}).get("bands") or []:
        blo, bhi = _lohi(b)
        if blo is None or _kind(b) != look:
            continue
        if abs(blo - lo) < 1e-9 and abs(bhi - hi) < 1e-9:
            return b
    return {}


def _band_block(doc, band, px) -> Optional[dict]:
    """One band, served: where it is, how thick, how proven."""
    lo, hi = _lohi(band)
    if lo is None:
        return None
    full = _stored_band(doc, band)
    return {"kind": _kind(band), "lo": lo, "hi": hi,
            "height_pct": _height_pct(band, px),
            "touches": int(_f(band.get("touches")) or _f(full.get("touches")) or 0),
            "strength": _f(full.get("strength")),
            "proven": bool((_f(band.get("touches")) or _f(full.get("touches")) or 0)
                           >= LID_MIN_TOUCHES)}


def _demand_bands_below(doc, px) -> list:
    """Every DEMAND band at or below the print, nearest first (highest top
    first). No threshold: a count of what is there, not a count of what is
    within some invented N% (the brief's s6 wants a measured quantile and
    there isn't one yet)."""
    p = _f(px)
    out = []
    if p is None or p <= 0:
        return out
    for b in (doc or {}).get("bands") or []:
        if _kind(b) != "demand":
            continue
        lo, hi = _lohi(b)
        if lo is None or lo > p:
            continue
        out.append(b)
    out.sort(key=lambda b: -float(b["hi"]))
    return out


def _same_range(a, b) -> bool:
    """True when two SERVED band blocks cover the very same price range.

    The store carries a supply cluster and a demand cluster over one range
    often enough that his own CRDO did it on 2026-09-16 — one shelf that was
    both the untested band the print was standing in and the floor under it —
    so the KIND is deliberately not compared: the question is whether the
    sentence is about to name one range twice. The numbers live in the tests
    and the doc, never here. Ends are compared at the same 6-dp rounding
    `_band_id` uses: they are copied floats everywhere in this path, so this
    only guards a number printed and re-parsed.
    """
    if not isinstance(a, dict) or not isinstance(b, dict):
        return False
    alo, ahi = _lohi(a)
    blo, bhi = _lohi(b)
    if alo is None or blo is None:
        return False
    return round(alo, 6) == round(blo, 6) and round(ahi, 6) == round(bhi, 6)


def _band_id(band) -> tuple:
    """A band's identity for set membership: kind + its two ends, rounded well
    inside a price tick. The ends are copied through as floats by every
    producer in this path, so this only guards a float printed and re-parsed."""
    lo, hi = _lohi(band)
    return (_kind(band),
            None if lo is None else round(lo, 6),
            None if hi is None else round(hi, 6))


def _untested_overhead(doc, px) -> list:
    """The overhead bands the engine DROPPED for want of touches.

    `bounce_room.overhead_bands` skips a band with fewer than
    `alert_gates.LID_MIN_TOUCHES` touches — the KLAC rule, and the right rule
    for a PHONE GATE: an untested lid is not a proven wall. It is the wrong
    rule for
    a SENTENCE that says "clear", because unproven is not absent, and it is the
    wrong rule for a RANK, because it fails open there instead of closed.

    So the same engine is asked twice — once as it stands, once with the touch
    count lifted to the minimum — and the DIFFERENCE is the untested set. Every
    other rule (broken supply, the gap day, a demand band price fell through)
    is the engine's own and is applied by the engine both times: nothing about
    which bands count as overhead is re-implemented here.
    """
    from supply_demand import bounce_room as BR                  # noqa: PLC0415

    p = _f(px)
    doc = doc or {}
    bands = doc.get("bands") or []
    if p is None or p <= 0 or not bands:
        return []
    prev = doc.get("prev_close")
    seen = {_band_id(b) for b in BR.overhead_bands(bands, p, prev)}
    lifted = []
    for b in bands:
        if not isinstance(b, dict):
            continue
        t = _f(b.get("touches"))
        lifted.append(dict(b, touches=LID_MIN_TOUCHES)
                      if t is not None and 0 < t < LID_MIN_TOUCHES else b)
    return [b for b in BR.overhead_bands(lifted, p, prev)
            if _band_id(b) not in seen]


