import { describe, it, expect, vi, beforeEach, afterEach } from 'vitest';
import { render, screen, waitFor, cleanup } from '@testing-library/react';
import { ShortInterestChip } from './ShortInterestChip';
import { ShortInterestPanel } from './ShortInterestPanel';
import { GgShortInterestLabel } from './GgShortInterestLabel';
import { GgSiExtremeNote } from './GgSiExtremeNote';
import { _resetShortInterestCache } from '../hooks/useShortInterest';
import { _resetRulesInfoCache } from '../hooks/useRulesInfo';

/* 🩳 FLOAT INCIDENTS — the served golden blocks through the REAL components (2026-11-26, spec floatguard rev 2 §4.6,
 * work package `fixtures`). Ajay 2026-11-26 ~21:20 ET: "Also the Float share count issue and SI discrepancy happened too
 * many times need to do something about it".
 *
 * Reads the SAME goldens the backend pins (backend/tests/fixtures/si_float_incidents_golden_2026_11_26.json and the
 * `hold` golden for cases 8, 9, 11), generated by backend/tests/test_si_float_incidents_2026_11_26.py from REAL captures.
 * For all 15 cases: the 🩳 chip prints block.chip with block.title on hover; the panel prints block.rows in order (the
 * `Float sources` row exactly when served); the 🎾 label prints the EXTREME note text when served, else the chip; the 👀
 * note prints extreme.short or nothing. Cases 8, 9, 11 keep the EXTREME note WITH the warning words.
 * NEGATIVES: NCPL's chip carries no warning; no case outside 8, 9, 11 carries it; from the hold golden a held name renders
 * no `gg-si-extreme` class and no 👀 note. The warning words are read from the served flag, never typed here.
 * No skip: a missing golden FAILS. */

const NODE = { fs: 'node:fs', path: 'node:path', url: 'node:url' };
const CONTESTED = ['8_CHWY_11_26', '9_GMEX_11_26', '11_DKI_11_26_widened'];
const FLOAT_SOURCES_ROW = 'Float sources';
const FLAG_KEY = 'sources_disagree';

type Flag = { key?: string; short?: string; text?: string };
type Block = {
  symbol: string; status: string; tier: string | null; chip: string | null; title: string;
  rows: { k: string; v: string }[];
  extreme: { text: string; short: string; title: string; basis: string } | null;
  basis?: { flags?: Flag[] } | null;
};
type Golden = { mode: string; blocks: Record<string, Block> };

async function loadGolden(name: string): Promise<Golden> {
  const fs = await import(/* @vite-ignore */ NODE.fs);
  const path = await import(/* @vite-ignore */ NODE.path);
  const url = await import(/* @vite-ignore */ NODE.url);
  const here = path.dirname(url.fileURLToPath(import.meta.url));
  const file: string = path.resolve(here, '../../../backend/tests/fixtures', name);
  if (!fs.existsSync(file)) throw new Error(`golden not found: ${file}`);
  const j = JSON.parse(fs.readFileSync(file, 'utf8'));
  if (!j || !j.blocks || Object.keys(j.blocks).length === 0) throw new Error(`no blocks in ${file}`);
  return j;
}
const gold = () => loadGolden('si_float_incidents_golden_2026_11_26.json');
const hold = () => loadGolden('si_float_incidents_hold_golden_2026_11_26.json');

function stub(sym: string, block: Block) {
  vi.stubGlobal('fetch', vi.fn(async (u: string) => {
    if (String(u).includes('/short-interest/map')) {
      return { ok: true, json: async () => ({ items: { [sym]: block }, n: 1, max_symbols: 200 }) } as unknown as Response;
    }
    return { ok: false, status: 404, json: async () => ({}) } as unknown as Response;
  }));
}

function flagShort(b: Block): string | undefined {
  return (b.basis?.flags || []).find((f) => f.key === FLAG_KEY)?.short;
}

async function draw(id: string, b: Block) {
  _resetShortInterestCache();
  stub(b.symbol, b);
  const r = render(
    <div>
      <ShortInterestChip symbol={b.symbol} />
      <ShortInterestPanel symbol={b.symbol} />
      <GgShortInterestLabel symbol={b.symbol} testid="gg-label" />
      <GgSiExtremeNote symbol={b.symbol} testid="gg-note" />
    </div>,
  );
  const panel = await screen.findByTestId('si-panel');
  await waitFor(() => expect(panel.querySelectorAll('dt').length, id).toBe(b.rows.length));
  return { ...r, panel };
}

describe('🩳 float incidents — served goldens through the real chip, panel, label and note', () => {
  beforeEach(() => { _resetShortInterestCache(); _resetRulesInfoCache(); });
  afterEach(() => { cleanup(); vi.unstubAllGlobals(); });

  it('the two goldens exist: 15 cases, the built mode, and the three held cases', async () => {
    const g = await gold();
    const h = await hold();
    expect(Object.keys(g.blocks).length).toBe(15);
    expect(g.mode).toBe('flag');
    expect(h.mode).toBe('hold');
    expect(Object.keys(h.blocks)).toEqual(CONTESTED);
  });

  it('every case: chip = block.chip + hover = block.title; panel rows verbatim; label and note as served', async () => {
    const { blocks } = await gold();
    for (const [id, b] of Object.entries(blocks)) {
      const { container, panel, unmount } = await draw(id, b);
      const chip = screen.getByTestId('si-chip');
      expect(chip.textContent, id).toBe(b.chip);
      expect(chip.getAttribute('title'), id).toBe(b.title);
      const rows = Array.from(panel.querySelectorAll('dt')).map((dt, i) => ({
        k: dt.textContent, v: panel.querySelectorAll('dd')[i]?.textContent,
      }));
      expect(rows, id).toEqual(b.rows);
      const label = screen.getByTestId('gg-label');
      const note = container.querySelector('[data-testid=gg-note]');
      if (b.extreme) {
        expect(label.textContent, id).toBe(b.extreme.text);
        expect(label.className, id).toContain('gg-si-extreme');
        expect(label.getAttribute('title'), id).toBe(b.extreme.title);
        expect(note?.textContent, id).toBe(b.extreme.short);
      } else {
        expect(label.textContent, id).toBe(b.chip);
        expect(label.className, id).not.toContain('gg-si-extreme');
        expect(note, id).toBeNull();
      }
      unmount();
      vi.unstubAllGlobals();
    }
  });

  it('the Float sources row prints in the panel exactly where it is served', async () => {
    const { blocks } = await gold();
    let withRow = 0;
    for (const [id, b] of Object.entries(blocks)) {
      const served = b.rows.find((r) => r.k === FLOAT_SOURCES_ROW);
      const { panel, unmount } = await draw(id, b);
      const dts = Array.from(panel.querySelectorAll('dt'));
      const i = dts.findIndex((dt) => dt.textContent === FLOAT_SOURCES_ROW);
      if (served) {
        withRow += 1;
        expect(i, id).toBeGreaterThanOrEqual(0);
        expect(panel.querySelectorAll('dd')[i]?.textContent, id).toBe(served.v);
      } else {
        expect(i, id).toBe(-1);
      }
      unmount();
      vi.unstubAllGlobals();
    }
    expect(withRow).toBe(11);
  });

  it('cases 8, 9, 11 keep the EXTREME note and it carries the served warning words', async () => {
    const { blocks } = await gold();
    for (const id of CONTESTED) {
      const b = blocks[id];
      const w = flagShort(b);
      expect(typeof w === 'string' && w.length > 0, id).toBe(true);
      const { unmount } = await draw(id, b);
      expect(screen.getByTestId('si-chip').textContent!.endsWith(w!), id).toBe(true);
      expect(screen.getByTestId('gg-note').textContent!.endsWith(w!), id).toBe(true);
      expect(screen.getByTestId('gg-label').className, id).toContain('gg-si-extreme');
      expect(screen.getByTestId('gg-label').textContent, id).toContain(w!);
      unmount();
      vi.unstubAllGlobals();
    }
  });

  it('NEGATIVE: NCPL and every other uncontested case print no warning words', async () => {
    const { blocks } = await gold();
    const w = flagShort(blocks['8_CHWY_11_26'])!;
    expect(w).toBeTruthy();
    for (const [id, b] of Object.entries(blocks)) {
      if (CONTESTED.includes(id)) continue;
      expect(flagShort(b), id).toBeUndefined();
      const { unmount } = await draw(id, b);
      expect(screen.getByTestId('si-chip').textContent, id).not.toContain(w);
      expect(screen.getByTestId('gg-label').textContent, id).not.toContain(w);
      unmount();
      vi.unstubAllGlobals();
    }
    expect(blocks['7_NCPL_11_26'].chip).not.toContain(w);
  });

  it('NEGATIVE (hold golden): a held name renders no gg-si-extreme class and no 👀 note, words kept', async () => {
    const { blocks } = await hold();
    for (const [id, b] of Object.entries(blocks)) {
      expect(b.extreme, id).toBeNull();
      const w = flagShort(b)!;
      const { container, unmount } = await draw(id, b);
      const label = screen.getByTestId('gg-label');
      expect(label.className, id).not.toContain('gg-si-extreme');
      expect(label.textContent, id).toBe(b.chip);
      expect(container.querySelector('.gg-si-extreme'), id).toBeNull();
      expect(container.querySelector('[data-testid=gg-note]'), id).toBeNull();
      expect(screen.getByTestId('si-chip').textContent!.endsWith(w), id).toBe(true);
      unmount();
      vi.unstubAllGlobals();
    }
  });
});
