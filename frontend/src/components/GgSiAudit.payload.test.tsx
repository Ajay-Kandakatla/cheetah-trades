import { fireEvent, render, screen, cleanup } from '@testing-library/react';
import { MemoryRouter } from 'react-router-dom';
import { afterEach, describe, expect, it, vi } from 'vitest';
import type { GgSiAuditBlock, GgSiAuditRow } from '../lib/gajjala';

/* 🧮 GgSiAuditSection — the SERVED audit golden through the real component (2026-11-26, spec floatguard rev 2 §4.6, work
 * package `fixtures`). Ajay 2026-11-26 ~21:20 ET: "Also the Float share count issue and SI discrepancy happened too many
 * times need to do something about it".
 *
 * Reads backend/tests/fixtures/si_source_audit_block_golden_2026_11_26.json — generated by short_interest.source_audit
 * .served_block and frozen by backend/tests/test_si_source_audit_2026_11_26.py (package be-audit). Pinned: the closed
 * fold's summary is the served summary; open → the served title, as-of, every served row in the served order with its
 * served cells under the served heads, `data-contested` / `data-held` exactly on the rows served so, the shown line, the
 * nested CLOSED rule fold → rule text + honesty. NEGATIVES: the counts (`n`, `n_differ`, `n_contested`, `n_window`) are
 * never printed on their own; an uncontested row carries no `data-contested`; with `fault_text` laid over the same golden
 * the section is one line and no table. No skip: a missing golden FAILS. */

vi.mock('../lib/usageTracker', () => ({ trackFeature: () => undefined }));

import { GgSiAuditSection } from './GgSiAudit';

const NODE = { fs: 'node:fs', path: 'node:path', url: 'node:url' };
const BLOCK_KEYS = ['title', 'summary_text', 'asof_text', 'heads', 'rows', 'shown_text', 'rule_label', 'rule_text',
  'honesty', 'fault_text', 'empty_text', 'n', 'n_differ', 'n_contested', 'n_window'];

async function loadBlock(): Promise<GgSiAuditBlock> {
  const fs = await import(/* @vite-ignore */ NODE.fs);
  const path = await import(/* @vite-ignore */ NODE.path);
  const url = await import(/* @vite-ignore */ NODE.url);
  const here = path.dirname(url.fileURLToPath(import.meta.url));
  const file: string = path.resolve(here, '../../../backend/tests/fixtures/si_source_audit_block_golden_2026_11_26.json');
  if (!fs.existsSync(file)) throw new Error(`audit golden not found: ${file}`);
  const j = JSON.parse(fs.readFileSync(file, 'utf8'));
  const b = j && typeof j === 'object' && j.block && typeof j.block === 'object' ? j.block : j;
  if (!b || typeof b !== 'object' || typeof b.summary_text !== 'string') throw new Error(`no served block in ${file}`);
  return b as GgSiAuditBlock;
}

const wrap = { wrapper: ({ children }: any) => <MemoryRouter>{children}</MemoryRouter> };
const openFold = (el: HTMLElement) => {
  (el as HTMLDetailsElement).open = true;
  fireEvent(el, new Event('toggle'));
};
const rowsOf = (b: GgSiAuditBlock) => (b.rows || []).filter((r): r is GgSiAuditRow => !!r && typeof r.symbol === 'string');

describe('🧮 audit golden → GgSiAuditSection, verbatim', () => {
  afterEach(() => { cleanup(); });

  it('the golden is a served block with every BLOCK_KEY', async () => {
    const b = await loadBlock();
    for (const k of BLOCK_KEYS) expect(Object.prototype.hasOwnProperty.call(b, k), k).toBe(true);
    expect(rowsOf(b).length).toBeGreaterThan(0);
  });

  it('closed by default: the summary is the served summary and no table is mounted', async () => {
    const b = await loadBlock();
    render(<GgSiAuditSection block={b} />, wrap);
    const fold = screen.getByTestId('gg-sa');
    expect((fold as HTMLDetailsElement).open).toBe(false);
    expect(screen.getByTestId('gg-sa-summary').textContent).toBe(b.summary_text);
    expect(screen.queryByTestId('gg-sa-table')).toBeNull();
  });

  it('open: title, as-of, every served row and cell under the served heads, the flags, the shown line', async () => {
    const b = await loadBlock();
    render(<GgSiAuditSection block={b} />, wrap);
    openFold(screen.getByTestId('gg-sa'));
    expect(screen.getByTestId('gg-sa-title').textContent).toBe(b.title);
    expect(screen.getByTestId('gg-sa-asof').textContent).toBe(b.asof_text);
    const heads = (b.heads || []) as [string, string][];
    expect(Array.from(screen.getByTestId('gg-sa-table').querySelectorAll('th')).map((th) => th.textContent))
      .toEqual(heads.map(([, label]) => label));
    const rows = rowsOf(b);
    const trs = Array.from(screen.getByTestId('gg-sa-table').querySelectorAll('tbody tr'));
    expect(trs.map((tr) => tr.getAttribute('data-testid'))).toEqual(rows.map((r) => `gg-sa-row-${r.symbol}`));
    rows.forEach((r, i) => {
      const tds = Array.from(trs[i].querySelectorAll('td')).map((td) => td.textContent);
      expect(tds[0], r.symbol as string).toBe(r.symbol);
      heads.slice(1).forEach(([k], j) => {
        const v = (r.cells || {})[k];
        expect(tds[j + 1], `${r.symbol} ${k}`).toBe(typeof v === 'string' ? v : '');
      });
      expect(trs[i].getAttribute('data-contested'), r.symbol as string).toBe(r.contested === true ? 'true' : null);
      expect(trs[i].getAttribute('data-held'), r.symbol as string).toBe(r.held === true ? 'true' : null);
    });
    if (typeof b.shown_text === 'string' && b.shown_text) {
      expect(screen.getByTestId('gg-sa-shown').textContent).toBe(b.shown_text);
    }
  });

  it('the rule fold is nested, closed, and holds the served rule text and honesty', async () => {
    const b = await loadBlock();
    render(<GgSiAuditSection block={b} />, wrap);
    openFold(screen.getByTestId('gg-sa'));
    const rule = screen.getByTestId('gg-sa-rule') as HTMLDetailsElement;
    expect(rule.open).toBe(false);
    expect(rule.querySelector('summary')?.textContent).toBe(b.rule_label);
    expect(screen.getByTestId('gg-sa-rule-text').textContent).toBe(b.rule_text);
    expect(screen.getByTestId('gg-sa-honesty').textContent).toBe(b.honesty);
  });

  it('NEGATIVE: the served counts are never printed on their own', async () => {
    const b = await loadBlock();
    const { container } = render(<GgSiAuditSection block={b} />, wrap);
    openFold(screen.getByTestId('gg-sa'));
    const leaves = Array.from(container.querySelectorAll('p, td, summary')).map((e) => (e.textContent || '').trim());
    for (const k of ['n', 'n_differ', 'n_contested', 'n_window'] as const) {
      const v = b[k];
      if (typeof v === 'number') expect(leaves, k).not.toContain(String(v));
    }
  });

  it('NEGATIVE: a served fault_text over the same golden is one line, no fold, no table', async () => {
    const b = await loadBlock();
    render(<GgSiAuditSection block={{ ...b, fault_text: b.summary_text }} />, wrap);
    expect(screen.getByTestId('gg-sa-fault').textContent).toBe(b.summary_text);
    expect(screen.queryByTestId('gg-sa')).toBeNull();
    expect(screen.queryByTestId('gg-sa-table')).toBeNull();
  });
});
