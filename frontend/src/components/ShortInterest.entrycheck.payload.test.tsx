import { describe, it, expect, vi, beforeEach, afterEach } from 'vitest';
import { render, screen, waitFor, cleanup } from '@testing-library/react';
import { ShortInterestChip } from './ShortInterestChip';
import { ShortInterestPanel } from './ShortInterestPanel';
import { GgShortInterestLabel } from './GgShortInterestLabel';
import { _resetShortInterestCache } from '../hooks/useShortInterest';
import { _resetRulesInfoCache } from '../hooks/useRulesInfo';
import FX from './__fixtures__/si_entry_check_2026_11_27.json';

/* 🩳 ON-ENTRY SOURCE CHECK — the served blocks through the REAL 🩳 chip, panel and 🎾 label (2026-11-27, spec sicheck
 * rev 2 §4.1, work package `si-pure`). Ajay 2026-11-27: "Can you double check short interest for these two please?"
 *
 * The fixture is GENERATED by backend/tests/test_si_entry_flags_2026_11_27.py from the REAL 2026-11-27 capture (pinned
 * equal there): BDMD served with the split-word read (flagged: `✂️ split filing 11/16 · ⚠️ sources disagree`), WHLR as
 * captured (its second float fails the house float check — NOT flagged), and the BDMD block main served before the
 * build (`old_payload`). This file types no chip word: every expected string is read from the served block.
 * NEGATIVES: WHLR carries no warning; the old payload renders as before; junk flags print nothing of their own. */

type Flag = { key?: string; short?: string; text?: string };
type Block = {
  symbol: string; status: string; chip: string | null; title: string;
  rows: { k: string; v: string }[];
  extreme: { text: string; short: string; title: string; basis: string } | null;
  basis?: { flags?: Flag[] } & Record<string, unknown> | null;
};
const F = FX as unknown as {
  flag_key: string; short_sources: string; short_split_filing: string;
  blocks: Record<string, Block>; old_payload: Block;
};

function stub(block: Block) {
  vi.stubGlobal('fetch', vi.fn(async (u: string) => {
    if (String(u).includes('/short-interest/map')) {
      return { ok: true, json: async () => ({ items: { [block.symbol]: block }, n: 1, max_symbols: 200 }) } as unknown as Response;
    }
    return { ok: false, status: 404, json: async () => ({}) } as unknown as Response;
  }));
}

async function draw(b: Block) {
  _resetShortInterestCache();
  stub(b);
  const r = render(
    <div>
      <ShortInterestChip symbol={b.symbol} />
      <ShortInterestPanel symbol={b.symbol} />
      <GgShortInterestLabel symbol={b.symbol} testid="gg-label" />
    </div>,
  );
  const panel = await screen.findByTestId('si-panel');
  await waitFor(() => expect(panel.querySelectorAll('dt').length).toBe(b.rows.length));
  const rows = Array.from(panel.querySelectorAll('dt')).map((dt, i) => ({
    k: dt.textContent, v: panel.querySelectorAll('dd')[i]?.textContent,
  }));
  return { ...r, panel, rows };
}

describe('🩳 on-entry source check — served blocks through the real chip, panel and label', () => {
  beforeEach(() => { _resetShortInterestCache(); _resetRulesInfoCache(); });
  afterEach(() => { cleanup(); vi.unstubAllGlobals(); });

  it('the fixture is the generated one: BDMD flagged, WHLR not, the old payload', () => {
    expect(Object.keys(F.blocks).sort()).toEqual(['BDMD_flagged', 'WHLR_not_flagged']);
    expect(F.blocks.BDMD_flagged.symbol).toBe('BDMD');
    expect(F.blocks.WHLR_not_flagged.symbol).toBe('WHLR');
    expect(F.old_payload.symbol).toBe('BDMD');
  });

  it('BDMD: the served chip prints verbatim and ends with the split-filing and sources-disagree words', async () => {
    const b = F.blocks.BDMD_flagged;
    const { rows } = await draw(b);
    const chip = screen.getByTestId('si-chip');
    expect(chip.textContent).toBe(b.chip);
    expect(chip.getAttribute('title')).toBe(b.title);
    expect(chip.textContent!.endsWith(` · ${F.short_split_filing} · ${F.short_sources}`)).toBe(true);
    expect(rows).toEqual(b.rows);
    expect(rows.some((r) => r.k === 'Split filing')).toBe(true);
    expect(screen.getByTestId('gg-label').textContent).toBe(b.chip);
    const served = (b.basis?.flags || []).map((f) => f.key);
    expect(served[served.length - 1]).toBe(F.flag_key);
  });

  it('NEGATIVE: WHLR prints its served chip verbatim with no sources-disagree words', async () => {
    const b = F.blocks.WHLR_not_flagged;
    const { rows } = await draw(b);
    const chip = screen.getByTestId('si-chip');
    expect(chip.textContent).toBe(b.chip);
    expect(chip.textContent).not.toContain(F.short_sources);
    expect((b.basis?.flags || []).some((f) => f.key === F.flag_key)).toBe(false);
    expect(rows).toEqual(b.rows);
    const src = rows.find((r) => r.k === 'Float sources');
    expect(src?.v).toContain('not used to flag the chip');
    expect(screen.getByTestId('gg-label').textContent).toBe(b.extreme ? b.extreme.text : b.chip);
  });

  it('NEGATIVE: the old payload (no new keys) renders exactly as served before the build', async () => {
    const b = F.old_payload;
    expect(b.basis && 'split_filings' in b.basis).toBe(false);
    const { rows } = await draw(b);
    expect(screen.getByTestId('si-chip').textContent).toBe(b.chip);
    expect(screen.getByTestId('si-chip').textContent).not.toContain(F.short_sources);
    expect(rows).toEqual(b.rows);
  });

  it('NEGATIVE: junk flags print nothing of their own — the served chip text is all that shows', async () => {
    const base = F.blocks.BDMD_flagged;
    for (const flags of [null, 'x', 3, [null, 7, { key: 'split_filing' }, { short: 42 }], [{ short: '' }]]) {
      const b = { ...base, chip: F.old_payload.chip, basis: { ...(base.basis || {}), flags } } as unknown as Block;
      const { unmount } = await draw(b);
      const chip = screen.getByTestId('si-chip');
      expect(chip.textContent).toBe(F.old_payload.chip);
      expect(chip.textContent).not.toContain(F.short_sources);
      expect(chip.textContent).not.toContain(F.short_split_filing);
      unmount();
      vi.unstubAllGlobals();
    }
  });
});
